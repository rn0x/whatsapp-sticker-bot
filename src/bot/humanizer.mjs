// تسمية عربية مقروءة لوضع المجموعة.
function modeLabel(mode) {
  const m = String(mode || "").toUpperCase();
  if (m === "OFF" || m === "off") return "معطلة";
  if (m === "MENTION_ONLY") return "بالإشارة فقط";
  if (m === "COMMAND_ONLY") return "بالأمر فقط";
  if (m === "AUTO") return "تلقائي";
  return "تلقائي";
}