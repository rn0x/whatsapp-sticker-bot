// Humanizer — يجعل البوت يتصرف كإنسان حقيقي: تأخيرات متنوعة، مؤشر كتابة،
// قراءة الرسائل، وصيغ ردود متناوبة. الغرض: تقليل خطر الحظر ونمطية الروبوت.
// الخصوصية: لا يسجّل محتوى الرسائل بل المدة/الحالة فقط.

export class Humanizer {
  constructor({ settings, logger }) {
    this.settings = settings;
    this.logger = logger;
    this._rotation = new Map(); // key -> index متناوب
  }

  enabled() {
    return this.settings.getBool("humanizer.enabled", true);
  }

  // تأخير عشوائي ضمن النطاق، مع تدرج حسب طول الرسالة (رسالة أطول = تفكير أطول قليلاً).
  replyDelay(bodyLength = 0) {
    if (!this.enabled()) return 0;
    const min = this.settings.getNumber("humanizer.replyDelayMinMs", 1500);
    const max = this.settings.getNumber("humanizer.replyDelayMaxMs", 7000);
    const base = min + Math.random() * Math.max(0, max - min);
    const boost = Math.min(2500, Math.max(0, (bodyLength || 0) - 20) * 40);
    return Math.round(base + boost);
  }

  // في انتظار المعالجة: إشارة "يكتب…" ثم توقف، كإنسان حقيقي.
  sendTyping(chatId) {
    if (!this.enabled() || !this.settings.getBool("humanizer.typingEnabled", true)) return;
    return this._presence(chatId, "typing").catch(() => {});
  }

  stopTyping(chatId) {
    if (!this.enabled() || !this.settings.getBool("humanizer.typingEnabled", true)) return;
    return this._presence(chatId, "paused").catch(() => {});
  }

  async _presence(chatId, state) {
    const { adapter } = this._adapterRef || {};
    if (adapter?.client?.sendPresenceUpdate) {
      await adapter.client.sendPresenceUpdate(state, chatId);
    }
  }

  setAdapter(adapter) {
    this._adapterRef = { adapter };
  }

  // صيغ متنوعة تُدار بالتناوب — لا تكرار حرفي لنفس الرد.
  pick(key, variants) {
    if (!Array.isArray(variants) || variants.length === 0) return "";
    const i = this._rotation.get(key) || 0;
    this._rotation.set(key, (i + 1) % variants.length);
    return variants[i];
  }
}

